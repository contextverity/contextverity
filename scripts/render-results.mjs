// Renders docs/results.md and the README results block from test-results/.
// Every number comes from the JSON files; nothing is typed by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = f => {
  const p = join(root, 'test-results', f);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : undefined;
};
const core = read('scenarios-core.json');
const live = read('scenarios-backstage.json');
const k8s = read('scenarios-kubernetes.json');
const benchCore = read('benchmarks-core.json');
const benchLive = read('benchmarks-backstage.json');
const telemetry = read('telemetry-backstage.json');
const network = read('kubernetes-network.json');

const pct = r =>
  r.value === null
    ? 'n/a'
    : `${(r.value * 100).toFixed(1)}% (${r.numerator}/${r.denominator})`;
const sha = c =>
  c && c !== 'uncommitted'
    ? `[\`${c.slice(
        0,
        12,
      )}\`](https://github.com/contextverity/contextverity/commit/${c})`
    : '`uncommitted`';
const env = e =>
  `ContextVerity ${e.contextverityVersion} · commit ${sha(e.commit)}${
    e.dirtyWorkingTree ? ' (with uncommitted changes)' : ''
  } · Backstage ${e.backstageRelease} · Node ${e.node} · ${e.platform} · ${
    e.cpu
  } (${e.cpuCount} cores, ${e.memoryGiB} GiB)`;

function summaryTable(r) {
  const s = r.summary;
  const o = s.observedOutcomes;
  return [
    '| Measure | Value |',
    '| --- | --- |',
    `| Scenarios defined | ${s.total} |`,
    `| Executed / passed / failed | ${s.executed} / ${s.passed} / ${s.failed} |`,
    `| Not applicable in this tier | ${s.unsupported} |`,
    `| Observed VALID / REFRESH / DENY / resolve refused | ${o.VALID} / ${o.REFRESH} / ${o.DENY} / ${o.RESOLVE_DENIED} |`,
    `| Stale-context detection rate | ${pct(s.metrics.staleDetectionRate)} |`,
    `| False invalidation rate | ${pct(s.metrics.falseInvalidationRate)} |`,
    `| False acceptance rate | ${pct(s.metrics.falseAcceptanceRate)} |`,
    `| DENY correctness | ${pct(s.metrics.denyCorrectness)} |`,
    `| REFRESH correctness | ${pct(s.metrics.refreshCorrectness)} |`,
    `| Resolve refusal correctness | ${pct(
      s.metrics.resolveRefusalCorrectness,
    )} |`,
  ].join('\n');
}

function scenarioTable(r) {
  const rows = r.scenarios.map(x => {
    const exp = x.expect.denialCode ?? x.expect.outcome;
    const obs = x.observed ? x.observed.denialCode ?? x.observed.outcome : '—';
    const codes = x.observed
      ? [
          ...x.observed.codes,
          ...x.observed.informational.map(c => `${c} (info)`),
        ].join(', ')
      : '';
    const status =
      x.status === 'UNSUPPORTED' ? `N/A — ${x.unsupportedReason}` : x.status;
    return `| ${x.id} | ${x.title} | ${x.group} | ${exp} | ${obs} | ${
      codes || '—'
    } | ${status} |`;
  });
  return [
    '| ID | Scenario | Group | Expected | Observed | Drift codes | Status |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

function benchTable(b) {
  const rows = b.results.map(
    r =>
      `| ${r.operation} | ${r.sources} | ${r.concurrency} | ${r.samples} | ${
        r.p50
      } | ${r.p95} | ${r.p99 ?? '—'} | ${r.throughputPerSec} |`,
  );
  return [
    '| Operation | Sources | Concurrency | Samples | p50 ms | p95 ms | p99 ms | Ops/s |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

const out = [
  '<!-- Generated by scripts/render-results.mjs from test-results/. Do not edit by hand. -->',
  '',
  '# Results',
  '',
  'Machine-generated from [`test-results/`](../test-results/). Regenerate with `make test-results`.',
  '',
  '> **Scope.** Synthetic catalog data, one machine. The live-lab and in-process results are separate measurements and are never combined. Perfect scores on a small synthetic scenario set do not imply production statistical confidence. See [testing.md](testing.md) for how each metric is defined.',
  '',
];

for (const [title, r] of [
  ['Live Backstage lab', live],
  ['Kubernetes (kind on Podman, Helm chart)', k8s],
  ['In-process core', core],
]) {
  if (!r) continue;
  out.push(
    `## Scenarios — ${title}`,
    '',
    `_${r.scope}_`,
    '',
    `Generated ${r.generatedAt}. ${env(r.environment)}`,
    '',
    summaryTable(r),
    '',
    '<details><summary>All scenarios</summary>',
    '',
    scenarioTable(r),
    '',
    '</details>',
    '',
  );
}
for (const [title, b] of [
  ['Live Backstage lab (end-to-end HTTP)', benchLive],
  ['In-process core', benchCore],
]) {
  if (!b) continue;
  out.push(
    `## Benchmarks — ${title}`,
    '',
    `_${b.scope}_`,
    '',
    `Generated ${b.generatedAt}. ${env(b.environment)}`,
    '',
    benchTable(b),
    '',
  );
}
if (telemetry) {
  out.push(
    '## Telemetry — live lab',
    '',
    `_${telemetry.scope}_`,
    '',
    `- ContextVerity root spans nested under Backstage MCP \`tools/call\` spans: **${telemetry.traces.nestedUnderMcpToolsCall}/${telemetry.traces.contextverityRootSpans}**`,
    `- Example chain: \`${telemetry.traces.exampleChain.join(' ← ')}\``,
    `- Span names: ${telemetry.traces.spanNames
      .map(n => `\`${n}\``)
      .join(', ')}`,
    `- Context values in span attributes: **${
      telemetry.traces.contextValuesInSpanAttributes ? 'yes' : 'no'
    }**`,
    `- Exposed metric names: ${telemetry.metrics.exposedNames
      .map(n => `\`${n}\``)
      .join(', ')}`,
    `- Metric label keys: ${telemetry.metrics.labelKeys
      .map(n => `\`${n}\``)
      .join(', ')}`,
    `- Check passed: **${telemetry.pass}**`,
    '',
  );
}
if (network) {
  out.push(
    '## Kubernetes network policy — live cluster',
    '',
    `Generated ${network.generatedAt}, commit ${sha(network.commit)}.`,
    '',
    '| Check | Observed | Result |',
    '| --- | --- | --- |',
    ...network.checks.map(
      c => `| ${c.name} | \`${c.observed}\` | ${c.pass ? 'pass' : 'FAIL'} |`,
    ),
    '',
  );
}
writeFileSync(join(root, 'docs/results.md'), `${out.join('\n')}\n`);

// README block: headline numbers only.
function firstPerSource(results) {
  const seen = new Set();
  return results.filter(
    r =>
      r.operation === 'receipt.verify' &&
      r.concurrency === 1 &&
      !seen.has(r.sources) &&
      seen.add(r.sources),
  );
}
const block = [];
if (live) {
  const s = live.summary;
  block.push(
    `**Live Backstage lab** (Backstage ${
      live.environment.backstageRelease
    }, synthetic data): ${s.passed}/${s.executed} executed scenarios passed (${
      s.unsupported
    } of ${
      s.total
    } need a controllable clock, outage injection, restart or second issuer and run in-process only). Stale-context detection ${pct(
      s.metrics.staleDetectionRate,
    )}, false invalidation ${pct(
      s.metrics.falseInvalidationRate,
    )}, false acceptance ${pct(s.metrics.falseAcceptanceRate)}.`,
  );
}
if (k8s) {
  const s = k8s.summary;
  const e = k8s.environment;
  block.push(
    `**On Kubernetes** (Helm chart on kind ${
      e.kind ?? ''
    } with Podman, Kubernetes ${e.kubernetes ?? ''}): ${s.passed}/${
      s.executed
    } executed scenarios passed, including a pod restart with the receipt surviving on the persistent volume (${
      s.unsupported
    } need a controllable clock, outage injection or second issuer). Stale-context detection ${pct(
      s.metrics.staleDetectionRate,
    )}, false invalidation ${pct(
      s.metrics.falseInvalidationRate,
    )}, false acceptance ${pct(s.metrics.falseAcceptanceRate)}.`,
  );
}
if (core) {
  const s = core.summary;
  block.push(
    `**In-process core** (synthetic catalog, Knex/SQLite store): ${s.passed}/${
      s.executed
    } scenarios passed. Stale-context detection ${pct(
      s.metrics.staleDetectionRate,
    )}, false invalidation ${pct(
      s.metrics.falseInvalidationRate,
    )}, false acceptance ${pct(s.metrics.falseAcceptanceRate)}.`,
  );
}
if (benchCore) {
  const v = firstPerSource(benchCore.results);
  block.push(
    `**In-process verification latency** (p50 / p95): ${v
      .map(
        r =>
          `${r.sources} source${r.sources > 1 ? 's' : ''} ${r.p50} / ${
            r.p95
          } ms`,
      )
      .join('; ')}.`,
  );
}
if (benchLive) {
  const v = firstPerSource(benchLive.results);
  block.push(
    `**Live-lab verification latency, end-to-end HTTP, development-mode backend** (p50 / p95): ${v
      .map(
        r =>
          `${r.sources} source${r.sources > 1 ? 's' : ''} ${r.p50} / ${
            r.p95
          } ms`,
      )
      .join('; ')}.`,
  );
}
if (core)
  block.push(
    `_Commit ${sha(core.environment.commit)}, generated ${core.generatedAt}._`,
  );
const readmePath = join(root, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const updated = readme.replace(
  /<!-- results:start -->[\s\S]*<!-- results:end -->/,
  `<!-- results:start -->\n${block.join('\n\n')}\n<!-- results:end -->`,
);
writeFileSync(readmePath, updated);
console.log('rendered docs/results.md and README results block');
